"""Validate editable JSON translations and build the offline browser bundle."""
from pathlib import Path
import json
import re

root = Path(__file__).resolve().parents[1]
game = root / 'game' if (root / 'game').is_dir() else root
locales = game / 'locales'
source = (locales / 'pt-BR.js').read_text(encoding='utf-8')
keys = set(json.loads(source[source.index('{'):source.rindex('}')+1]))
languages = json.loads((locales / 'languages.json').read_text(encoding='utf-8'))
assert len({item['code'] for item in languages}) == len(languages), 'Duplicate language code'
output = ['// Generated by tools/build-locales.py; edit locales/*.json.\n',
          '// Translation adaptations: CC BY-NC-SA 4.0. See License.txt.\n']
for item in languages:
    dictionary = json.loads((locales / (item['code'] + '.json')).read_text(encoding='utf-8'))
    assert set(dictionary) == keys, item['code'] + ': missing or unexpected source keys'
    for key, value in dictionary.items():
        assert isinstance(value, str) and value.strip(), item['code'] + ': empty ' + key
        assert re.findall(r'\{\w+\}', key) == re.findall(r'\{\w+\}', value), item['code'] + ': placeholder mismatch ' + key
    output.append('Localization.registerLanguage(' + json.dumps(item['code']) + ', ' +
                  json.dumps(item['name'], ensure_ascii=False) + ', ' +
                  json.dumps(dictionary, ensure_ascii=False, indent=2) + ');\n')
(locales / 'catalogs.js').write_text(''.join(output), encoding='utf-8', newline='\n')
print(f"Built {len(languages)} additional languages, {len(keys)} strings each")
